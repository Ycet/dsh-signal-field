/**
 * dsh-signal-field · 零依赖构建脚本
 *
 * 为什么不用 esbuild：本机 `npm` 存在 `~/.npm` 权限问题，而 Client bundle 的产物格式
 * 非常简单（`window.__ModuleLoader__.load({ id, factory })`），用 Node 内置能力拼接即可，
 * 既不需要联网安装依赖，也让 `src/*.js` 保持可被 `node --test` 直接导入的 ES 模块形态。
 *
 * 书写约定（脚本会校验，违反即构建失败）：
 *   1. `src/*.js` 是 ES 模块；`import` 语句必须单行写完并以 `;` 结束，且位于文件顶部；
 *   2. 只有声明行使用 `export` 前缀，不做 `export *` / `export default`；
 *   3. `import React from "react"` 只为编辑器与单元测试提供信息，构建时剥离；
 *      产物里的 `React` / `h` 由构建注入的前导代码提供。
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** 拼接顺序即依赖顺序：被依赖者在前。 */
const ORDER = [
  'src/settings.js',
  'src/page.js',
  'src/glsl.js',
  'src/field.js',
  'src/techtext.js',
  'src/styles.js',
  'src/stage.js',
  'src/settings-page.js',
  'src/client.js',
];

const PACKAGE = JSON.parse(await readFile(join(ROOT, 'package.json'), 'utf8'));

/** 剥离 import 语句与 export 前缀，得到可放进同一闭包的脚本体。 */
function stripModuleSyntax(source, file) {
  const lines = source.split('\n');
  const out = [];
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    const trimmed = line.trim();

    if (trimmed.startsWith('import ')) {
      if (!trimmed.endsWith(';')) {
        throw new Error(`${file}:${index + 1} import 必须单行写完并以 ; 结束：${trimmed}`);
      }
      continue;
    }
    if (trimmed.startsWith('export default') || trimmed.startsWith('export *')) {
      throw new Error(`${file}:${index + 1} 不支持 export default / export *，请改为具名导出。`);
    }
    // 只剥离声明行行首的 `export `，保留原缩进。
    out.push(line.replace(/^(\s*)export\s+(?=(?:async\s+)?(?:function|const|let|var|class)\b)/, '$1'));
  }
  return out.join('\n');
}

/** 读取 locale/*.json，取出运行时字典（meta 由插件管理器直接读 JSON，不进包体）。 */
async function readDicts() {
  const dicts = {};
  for (const locale of ['zh', 'en']) {
    const raw = await readFile(join(ROOT, 'locale', `${locale}.json`), 'utf8');
    const parsed = JSON.parse(raw);
    const meta = parsed && parsed.meta;
    if (!meta || typeof meta.title !== 'string' || typeof meta.description !== 'string') {
      throw new Error(`locale/${locale}.json 缺少 meta.title / meta.description`);
    }
    const runtime = parsed && parsed.runtime;
    if (!runtime || typeof runtime !== 'object' || Array.isArray(runtime)) {
      throw new Error(`locale/${locale}.json 缺少 runtime 字典`);
    }
    dicts[locale] = runtime;
  }
  return dicts;
}

/** 执行一次构建，返回产物路径与体积。 */
export async function build() {
  const chunks = [];
  for (const relative of ORDER) {
    const source = await readFile(join(ROOT, relative), 'utf8');
    chunks.push(`// ---- ${relative} ----\n${stripModuleSyntax(source, relative)}`);
  }

  const dicts = await readDicts();
  const localeBlock = `var SIGNAL_FIELD_DICTS = ${JSON.stringify(dicts, null, 2)};`;

  const body = [
    'var React = require("react");',
    'var h = React.createElement;',
    localeBlock,
    chunks.join('\n\n'),
    'module.exports = { inject: inject, apply: apply };',
  ].join('\n');

  // 校验一：拼接后不应再残留模块语法。
  const bodyLines = body.split('\n');
  const leftover = bodyLines.findIndex((line) => {
    const trimmed = line.trim();
    return trimmed.startsWith('import ') || trimmed.startsWith('export ');
  });
  if (leftover >= 0) {
    throw new Error(`构建产物第 ${leftover + 1} 行残留模块语法：${bodyLines[leftover]}`);
  }

  // 校验二：产物必须是合法 JavaScript（只解析，不执行）。
  try {
    new Function(body);
  } catch (error) {
    throw new Error(`构建产物语法错误：${error && error.message}`);
  }

  const output = [
    '// Generated by scripts/build.mjs. Do not edit by hand.',
    'window.__ModuleLoader__.load({',
    `  id: ${JSON.stringify(PACKAGE.name)},`,
    '  factory: (require) => {',
    '    var module = { exports: {} };',
    '    var exports = module.exports;',
    bodyLines.map((line) => (line === '' ? '' : `    ${line}`)).join('\n'),
    '    return module.exports;',
    '  },',
    '});',
    '',
  ].join('\n');

  await mkdir(ROOT, { recursive: true });
  const target = join(ROOT, 'client.js');
  await writeFile(target, output, 'utf8');
  return { target, bytes: Buffer.byteLength(output) };
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  const result = await build();
  console.log(`built ${result.target} (${result.bytes} bytes)`);
}
